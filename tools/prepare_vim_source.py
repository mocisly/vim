#!/usr/bin/env python3
"""Mirror pristine Vim into the build tree and apply integration patches."""

import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess


def signature(source: Path, patches: list[Path]) -> str:
    digest = hashlib.sha256()
    for directory, folders, files in os.walk(source):
        folders.sort()
        for name in sorted(files):
            path = Path(directory) / name
            metadata = path.stat()
            relative = path.relative_to(source).as_posix()
            digest.update(f"{relative}\0{metadata.st_size}\0{metadata.st_mtime_ns}\n".encode())
    for patch in patches:
        digest.update(patch.name.encode())
        digest.update(patch.read_bytes())
    return digest.hexdigest()


def patched(source: Path) -> bool:
    cmake = source / "CMakeLists.txt"
    alloc = source / "src/alloc.c"
    return (
        cmake.is_file()
        and alloc.is_file()
        and 'include("${VIM_INTEGRATION_ROOT}/cmake/VimCore.cmake")' in cmake.read_text()
        and "static VIM_INSTANCE_TLS int" in alloc.read_text()
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--build-root", type=Path, required=True)
    parser.add_argument("--adopt-existing", action="store_true")
    parser.add_argument("patches", type=Path, nargs="+")
    args = parser.parse_args()

    repo = args.repo.resolve()
    source = args.upstream.resolve()
    build_root = args.build_root.resolve()
    target = build_root / "vim-source"
    patches = [path.resolve() for path in args.patches]
    if not source.is_relative_to(repo / "upstream") or not (source / "src").is_dir():
        parser.error("Upstream Vim must be under this project's upstream directory")
    if build_root == repo or build_root.is_relative_to(source) or target.resolve() != target:
        parser.error("Unsafe generated source directory")
    if not all(path.is_file() and path.is_relative_to(repo / "patches") for path in patches):
        parser.error("Patch paths must be under this project's patches directory")
    if not target.is_relative_to(repo):
        parser.error("The build directory must be inside this project")

    current_signature = signature(source, patches)
    stamp = target / ".vim-source-signature"
    if stamp.is_file() and stamp.read_text() == current_signature and patched(target):
        print("Vim source mirror is current")
        return

    if args.adopt_existing:
        if not patched(target):
            parser.error("Cannot adopt an unpatched source mirror")
        stamp.write_text(current_signature)
        print("Adopted existing patched Vim source mirror")
        return

    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(source, target)
    pathdef = target / "src/auto/pathdef.c"
    if not pathdef.exists():
        pathdef.parent.mkdir(parents=True, exist_ok=True)
        pathdef.write_text("/* Generated by pathdef.bat during configuration. */\n")
    relative_target = target.relative_to(repo).as_posix()
    for patch in patches:
        subprocess.run(
            ["git", "apply", f"--directory={relative_target}", "--whitespace=nowarn", str(patch)],
            cwd=repo, check=True,
        )
    if not patched(target):
        raise RuntimeError("Patch application did not produce the expected Vim sources")
    stamp.write_text(current_signature)
    print("Prepared patched Vim source mirror")


if __name__ == "__main__":
    main()
